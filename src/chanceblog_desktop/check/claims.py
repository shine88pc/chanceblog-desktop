def _conditioned(tail):
    """낱말 바로 뒤에 '하지 않은 일' 표지(…한 적이 없다·…했다면·…하시면)가 있는가 — 다만 그 사이에 겪은 일을 단정하는 서술어가 끼면('…편합니다 궁금하시면 물어보세요') 앞의 말은 조건이 아니다."""
    found = _RIGHT_GUARD_RE.search(tail)
    return bool(found) and (found.group(0) in _CASE_GUARDS or not _ASSERT.search(tail, 0, found.start()))


def _asserted(flat_sentence, match, starts=None, asked=False):
    """부탁·질문으로 끝나는 말 안의 '써 본·다녀온' 이 아니라 겪은 일을 단정하는 서술어(…편합니다·…산 제품이니·…좋습니다) 뒤에 부탁이 덧붙은 말인가. 평가·짐작·추천 끝말(…좋습니다·…수 있습니다·…것 같아요·…권합니다)도 안내 틀
    ('…하는 것이 좋습니다')이 아니면 단정으로 본다 — 주어를 줄인 '써 본 결과 만족할 수 있습니다' 를 놓치지 않으려는 것이다(높임 '…남기실 수 있습니다' 는 1인칭·때 표지가 없을 때만 독자에게 하는 말). 낱말 뒤 `ASSERT_SPAN` 글자 안에서 독자에게 하는 말이 시작되는 자리까지만 본다."""
    start = match.end()
    marked = _SELF_MARK.search(flat_sentence, max(0, match.start() - FIRST_SPAN), start)
    cut = (_CUT_ASKED if asked and marked else _CUT_ASKED_READER if asked else _CUT if marked else _CUT_READER).search(flat_sentence, start, start + ASSERT_SPAN)
    stop = cut.start() if cut else start + ASSERT_SPAN
    if _ASSERT.search(flat_sentence, start, stop):
        return True
    if not cut:
        return False
    return _clause_between(flat_sentence, start, stop, match.group(0), starts() if starts else None)


def _writer_leads(flat_sentence, begin, end, boundary):
    """꾸미는 낱말(`begin`~`end`) 앞 `WRITER_SPAN` 글자 안에 글쓴이를 가리키는 1인칭('제가·저는·내가·저도·저희는·우리는·우리가')이 한 낱말로 서 있는가 — 낱말이 시작하고 끝나는 자리에서만 센다('요금제가' 속 '제가'·'우리가족이' 속 '우리가' 는 낱말의 일부다)."""
    return any(found.start() in boundary and found.end() in boundary for found in _WRITER.finditer(flat_sentence, max(0, begin - WRITER_SPAN), end))


def _clause_between(flat_sentence, start, stop, word, boundary):
    """꾸미는 낱말 뒤 ~ 부탁 앞의 말이 부탁의 목적어가 아니라 따로 선 서술 절인가 — 서술 어미가 무엇이든 가르는 구조 판정이다('표지 + 서술 절 + 부탁 꼬리').
    낱말의 머리말('느낌·후기·결과')에 조사가 붙어 부탁의 목적어·때가 된 꼴('써 본 느낌을 댓글로 편하게 남겨 주세요')은 그 조사가 낀 낱말 뒤 `PLAIN_SPAN` 글자까지, 조사가 없거나 주제로 세운 꼴('써 본 결과 …'·'다녀온 후기로는 …')은
    `CLAUSE_SPAN` 글자까지만 부탁의 말로 보고 그보다 길게 이어지면 서술 절로 본다(부탁 자신인 끊는 자리의 낱말은 세지 않는다). 조건('…나면')이 낀 말은 독자에게 하는 안내다.
    글쓴이를 가리키는 1인칭이 꾸미는 낱말 앞 `WRITER_SPAN` 글자 안에 낱말로 서 있고(`_writer_leads`) 부탁 꼬리가 그 경험을 근거로 권하는 말(`_RECOMMEND` — '참고하세요'·'확인해 주세요'·'써 보세요' …)이면, 아래의 이어 가는 낱말·조건('…면') 검사를 지난 뒤 서술 절이 얼마나 짧든 '제가 직접 써 본 결과 편해서 참고하세요' 처럼 겪은 일을 단정한 말이다 —
    독자에게 경험을 청하는 부탁('제가 올린 사진을 보고 써 본 느낌을 댓글로 알려 주세요')과 독자에게 거는 조건 안내('…막히면 질문하세요')는 이 규칙으로 걸지 않는다(꼬리가 추천류가 아닌 단정도 이 규칙으로는 못 건다) —
    다만 사이가 비어 있거나('제가 써 본 느낌을 알려 드릴게요') 부탁 꼬리가 글쓴이 자신의 앞으로의 계획·다짐('…알려 드릴게요'·'…올릴 예정입니다')이거나 절이 계획을 이유로 이어 가면('…올릴 테니 참고하세요') 1인칭은 그 계획의 주어이므로 이 규칙을 쓰지 않는다 —
    꾸미는 낱말이 '써 본 분의 후기'·'다녀온 분을' 처럼 해 본 사람을 가리키면('저는 써 본 적이 없어서 직접 써 본 분의 후기를 참고하세요') 그 경험은 글쓴이 것이 아니다.
    `boundary` 는 낱말이 시작하는 자리(띄어 쓴 글만) — 붙여 쓴 글은 머리말을 알아볼 수 없어 서술 절 쪽(엄격)으로 본다(낱말 경계를 모르면 '요금제가' 속 '제가' 를 가를 수 없어 1인칭 규칙도 쓰지 않는다)."""
    if boundary is None:
        return stop - start > CLAUSE_SPAN + REQUEST_WORD_SIZE
    begin, limit = start, CLAUSE_SPAN
    if (start in boundary and word.endswith(_ADNOMINAL)) or start not in boundary:           # '써 본|후기를'·'느낌|을' — 머리말 낱말(조사가 붙은 것까지)이 끝나는 자리부터 센다
        begin = next((place for place in range(start + 1, stop + 1) if place in boundary), stop)
        if flat_sentence.endswith(_ARGUMENT, start, begin) and not flat_sentence.endswith("결과", start, begin):          # '결과' 의 '과' 는 조사가 아니다
            limit = PLAIN_SPAN
    end = stop - 1 if stop in boundary else stop                                                       # 끊는 자리의 낱말('남겨 |주세요'·'참고|하세요')은 부탁 자신이다 — 그 앞까지만 센다
    while end > begin and end not in boundary:
        end -= 1
    if word.endswith(_CONNECTIVE_END):
        return False
    if any(place in boundary and flat_sentence[place - 1] == "면" and not flat_sentence.endswith(_WRITER_IF, 0, place) for place in range(begin + 1, stop + 1)):          # 조건절('오류가 나면 …')은 서술이 아니라 안내다 — 글쓴이가 말을 잇는 '풀어 보자면'은 아니다
        return False
    if end > begin and _writer_leads(flat_sentence, start - len(word), start, boundary) and not _PLEDGE.match(flat_sentence, stop) and flat_sentence.find(_PLAN_CLAUSE, begin, end) < 0 and not flat_sentence.startswith(_OTHERS, start) and _RECOMMEND.search(flat_sentence, end, stop + REQUEST_SPAN) and not flat_sentence.endswith(("을", "를"), begin, end):
        return True                                                                                    # '제가 직접 써 본 결과 편해서 참고하세요' — 글쓴이 자신이 겪은 일을 서술한 절이고 꼬리가 그 경험을 근거로 권하는 말이다(절이 얼마나 짧든 — 이어 가는 낱말·조건('…면')은 위에서 먼저 지나가고, 절이 '…을·…를' 로 끝나면 꼬리가 받는 목적어('결과를 확인해 주세요')라 독자에게 순서를 안내하는 말이므로 걸지 않는다 — 추천 낱말은 끊는 자리 뒤 `REQUEST_SPAN` 글자까지만 찾는다(긴 한 문장에서 제곱 시간이 되지 않게))
    if limit == PLAIN_SPAN and any(place in boundary and flat_sentence[place - 1] in _SUBJECT for place in range(begin + 1, end + 1)):          # 조사가 붙은 머리말 뒤에 자기 주어를 가진 말('남기니 많은 도움이 되길')이 끼면 목적어가 아니라 서술 절이다
        limit = CLAUSE_SPAN
    return end - begin > limit


def _guarded(flat_sentence, match, extra_start):
    """걸린 낱말이 '하지 않은 일'(…한 적이 없다·…했다면·…한 것처럼·…했다고 해서)을 말하는 자리에 있는가."""
    tail = flat_sentence[match.end():match.end() + RIGHT_SPAN + 4].replace("아닌가요", "")[:RIGHT_SPAN]           # '…했습니다 아닌가요?' 의 '아닌' 은 부정이 아니라 되묻는 꼬리다(창 끝에서 잘리지 않게 넉넉히 잡고 지운 뒤 자른다)
    word = match.group(0)
    made = word.find("만들어")
    if made >= 0 and flat_sentence[max(0, match.start() + made - 5):match.start() + made].endswith(_MADE_AS):          # '표로 만들어 보았습니다' 는 글에 넣을 표를 만든 일이지 겪은 일이 아니다
        return True
    if _REPORT_WORD.search(word) and any(hint in tail for hint in _HOW_TO):                                              # '다녀온 후기를 남기는 방법' — 쓰는 법을 안내하는 말
        return True
    if word in ("제친구", "제지인") and flat_sentence[max(0, match.start() - 1):match.start()] in ("어", "그"):          # '어제 친구'·'그제 지인'
        return True
    if word.endswith("봤") and tail.startswith("자"):                                                                 # '열어 봤자 소용없다'
        return True
    if word.endswith(("알려", "추천해", "권해", "소개해")) and tail.startswith(("준", "주는", "주던", "주신", "줄")):                 # '지인이 알려 준 정보' — 뒤의 말을 꾸미는 모양이지 겪은 일의 보고가 아니다
        return True
    return bool(_conditioned(tail) or tail.startswith(_RIGHT_START) or (extra_start and tail.startswith(extra_start) and not _OWN_VIEW.match(tail))
                or (word[-1] in "한본온" and tail.startswith(_NOUN_START)))


def _unguarded(flat_sentence, pattern, extra_start, modifier_ok=False, finite_ok=False, when_ok=False, starts=None):          # when_ok = 묻는 말
    """첫 번째로 걸리는 경험 단정 낱말(바로 뒤에 '하지 않은 일' 표지가 없는 것). 없으면 None.
    `modifier_ok` — 부탁·안내·질문이라 '써 본 느낌'·'다녀온 후기' 같은 꾸미는 모양은 지나가게 한다. `finite_ok` — 독자에게 묻는 말이라 '써 보니' 같은 끝맺은 모양도 지나가게 한다.
    `when_ok` — 독자에게 묻는 말에서 '직접 써 봤을 때 어떠셨나요?' 처럼 때를 가리키는 말('…을 때')이 바로 이어지는 것도 지나가게 한다."""
    for match in pattern.finditer(flat_sentence):
        word = match.group(0)
        if _guarded(flat_sentence, match, extra_start):
            continue
        if word.endswith(("적이었습니다", "적이었다")) and _TOPIC_BEFORE.search(flat_sentence, max(0, match.start() - 9), match.start()):          # 이 낱말은 주어를 설명하는 말('일반적·역사적·긍정적')이라 겪은 일이 아니다 — 주어 없이 홀로 선 말과 목록의 '인상적이었' 류는 그대로 건다
            continue
        if word in ("봤", "보았", "보니"):                                                                  # 이은 글자만 보고 잡은 '…어 봤' — 앞 낱말이 알아보거나 따져 본 일이면 겪은 일이 아니다
            before = flat_sentence[max(0, match.start() - 8):match.start()]
            if before.endswith(_COGNITIVE) or before.endswith(_NEUTRAL_HAE):
                continue
        elif "봤" in word and any(stem + "봤" in word for stem in _COGNITIVE):                   # '자료를 알아봤다' 는 겪은 일이 아니다
            continue
        if when_ok and flat_sentence.startswith("을때", match.end()):
            continue
        if _MODIFIER_WORD.search(word):
            if modifier_ok and not _asserted(flat_sentence, match, starts, when_ok):           # 부탁·질문이어도 겪은 일을 단정한 뒤에 부탁을 덧붙인 말은 면제하지 않는다
                continue
        elif finite_ok:
            continue
        return word
    return None


def _word_starts(sentence):
    """`flat` 글에서 낱말이 시작하는 자리(원래 글에서 띄어쓰기·구두점 바로 뒤)의 번호들 — '끝나는' 속의 '나는' 을 글쓴이를 가리키는 말로 읽지 않으려고 쓴다."""
    text = unicodedata.normalize("NFKC", _INVISIBLE.sub("", str(sentence))).casefold()
    starts, removed = {0}, 0
    for match in _NOT_ALNUM.finditer(text):
        starts.add(match.start() - removed)
        removed += match.end() - match.start()
    return starts


def _narrative(sentence, flat_sentence, finite_ok, survey=False):
    """겪은 일을 말하는 과거형 서술 — (분류, 낱말). ① 글쓴이를 가리키는 말('제가·저는 …') 뒤 가까이 ② 표지 없이도 일상을 겪은 말로만 읽히는 동사 ③ 해요체 과거형. 글 쓰는 일·생각을 말하는 것과
    '…했다면·…한 적 없다·…했다고 한다' 는 뺀다."""
    if finite_ok:
        return None
    starts = None
    signalled = None
    spaced = bool(_SPACED.search(sentence))
    for pattern, marked in ((_NARRATIVE, True), (_PERSONAL, False), (_CASUAL, False)):
        if survey and not marked:
            continue
        if pattern is _PERSONAL and spaced and pattern.search(flat_sentence):          # 붙여 쓴 글은 낱말 경계를 몰라 3인칭 주어를 알아볼 수 없다 — 건너뛰지 않는다
            starts = _word_starts(sentence) if starts is None else starts
            if any(found.start() in starts for found in _THIRD.finditer(flat_sentence)):
                continue
        if pattern is _CASUAL:
            if signalled is None:                                                # 신호 낱말은 (띄어 쓴 글에서는) 낱말이 시작하는 자리에서만 센다('요금제가' 속 '제가' 는 글쓴이가 아니다)
                if spaced:
                    starts = _word_starts(sentence) if starts is None else starts
                signalled = any(not spaced or found.start() in starts for found in _PERSONAL_SIGNAL.finditer(flat_sentence))
            if not signalled:
                continue
        for match in pattern.finditer(flat_sentence):
            word = match.group(0) if marked else flat_sentence[max(0, match.start() - 4):match.end()]
            if any(skip in word for skip in _NARRATIVE_SKIP) or _guarded(flat_sentence, match, () if marked else _QUOTED_START):
                continue
            if marked:
                if starts is None:
                    starts = _word_starts(sentence)
                if match.start() not in starts:
                    continue
            for category, stems in _NARRATIVE_KINDS:
                if any(stem in word for stem in stems):
                    return category, word
            return EXPERIENCE_USE, word
    return None


def _timed(flat_sentence, soft):
    """'…했을 때'·'한 고객이' 형태 — 같은 문장 뒤에 (글 쓰는 일이 아닌) 과거형 서술이 있고 문장이 안내로 끝나지 않을 때만(`soft` 는 호출하는 쪽이 있을 때만 넘긴다)."""
    match = soft.search(flat_sentence)                              # 첫 낱말만 본다 — 뒤에 과거형 서술이 있으면 첫 낱말 뒤에도 있다(낱말마다 찾으면 긴 글에서 제곱 시간)
    if not match or _ADVICE_END.search(flat_sentence):
        return None
    for seen, past in enumerate(_PAST.finditer(flat_sentence, match.end())):
        if not _META_PAST.search(flat_sentence, max(match.end(), past.start() - 4), past.start() + 1):
            return match.group(0)
        if seen >= 2:                                               # 앞의 세 곳만 본다(긴 글에서 늘어지지 않게)
            break
    return None


class _Mood:
    """문장의 말투 — 규칙에 걸린 낱말이 있을 때만 한 번 계산한다(걸린 것이 없는 문장에서는 시간을 쓰지 않는다)."""
    __slots__ = ("calm", "unasked", "asked", "survey", "_sentence", "_starts")

    def __init__(self, sentence, flat_sentence):
        self._sentence, self._starts = sentence, False
        asks = _asks(sentence, flat_sentence)
        past = asks and _states_past(flat_sentence)
        self.asked = asks and not past                                                   # 겪은 일을 서술하는 과거형 없이 묻는 말
        self.unasked = self.asked and not _SELF_MARK.search(flat_sentence)               # 독자에게 묻는 말 — 1인칭·때 표지도 없다('써 보니 어떠셨나요?'). 표지가 있으면 묻는 꼴로 위장한 선언이다
        self.calm = self.asked or ((bool(_REQUEST_END.search(flat_sentence[-REQUEST_SPAN:])) or bool(_REQUEST_MID.search(flat_sentence))) and not _FINITE_RE.search(flat_sentence))          # 묻거나 부탁하는 말이고 겪은 일을 서술하는 과거형은 없다 — '써 본 느낌을 알려 주세요'
        self.survey = bool(_SURVEY.search(flat_sentence)) or "%" in sentence             # 조사에 응한 사람들의 대답을 옮기는 말(`DIALOGUE` 만 본다)

    def starts(self):
        """띄어 쓴 글이면 낱말이 시작하는 자리들(`flat` 글 기준), 붙여 쓴 글이면 None — 처음 부를 때만 계산한다."""
        if self._starts is False:
            self._starts = _word_starts(self._sentence) if _SPACED.search(self._sentence) else None
        return self._starts


def _violations(sentence, flat_sentence):
    found, mood = [], None
    for category, patterns, soft, extra_start in _COMPILED:
        word = None
        if patterns.search(flat_sentence):
            mood = mood or _Mood(sentence, flat_sentence)
            if not (category == DIALOGUE and mood.survey):
                word = _unguarded(flat_sentence, patterns, extra_start, mood.calm, mood.unasked, mood.asked, mood.starts)
        if not word and soft is not None and soft.search(flat_sentence):
            mood = mood or _Mood(sentence, flat_sentence)
            word = None if mood.asked else _timed(flat_sentence, soft)
        if word:
            found.append((category, word))
    if _UNMARKED_ANY.search(flat_sentence):
        mood = mood or _Mood(sentence, flat_sentence)
        narrative = _narrative(sentence, flat_sentence, mood.unasked, mood.survey)
        if narrative and all(category != narrative[0] for category, _ in found):
            found.append(narrative)
    if _ASCII_WORDS.search(sentence):
        mood = mood or _Mood(sentence, flat_sentence)
        if not mood.asked:
            lowered = sentence.casefold()
            for category, pattern in _EN_RULES:
                match = pattern.search(lowered)
                if match:
                    found.append((category, match.group(0)))
    return found


def _past_syllable(char):
    code = ord(char) - 0xAC00
    return 0 <= code < 11172 and code % 28 == 20 and char not in "셨겠있"          # 받침이 'ㅆ' 인 글자 — 과거형(았·었·했·였·봤·썼 …). 높임의 '셨'(어떠셨어요?)·추측·부탁의 '겠'(알려 주시겠어요?)·있다의 '있'(있어요) 은 과거 서술이 아니므로 뺀다


def _states_past(flat_sentence):
    """문장에 과거형 서술(-았어요·-했습니다·-했네요·-했군요, 맨 끝의 -했다)이 있는가 — '어땠어요' 같은 묻는 낱말은 서술로 치지 않는다."""
    text = _ASKING_WORD.sub("", flat_sentence)
    if len(text) > 1 and text.endswith("다") and _past_syllable(text[-2]):
        return True
    return any(match.start() and _past_syllable(text[match.start() - 1]) for match in _PAST_STATEMENT.finditer(text))


def _asks(sentence, flat_sentence):
    """묻는 말로 끝나는가('써 보니 어떠셨나요?') — 겪은 일을 서술하는 과거형이 있는 문장('편했어요?'·'좋았죠?')이 묻는 말인지는 호출하는 쪽이 `_states_past`·`_SELF_MARK` 로 따로 본다.
    끝의 닫는 따옴표·괄호는 `flat` 이 이미 지웠으므로 물음표는 글 그대로의 끝에서, 묻는 어미는 `flat` 글의 끝에서 본다."""
    stripped = sentence.rstrip().rstrip("\"')]”’」』").rstrip()
    return stripped.endswith(("?", "？")) or bool(_QUESTION_END.search(flat_sentence[-8:]))


def _sentences(text_or_sentences, item="검사할 글"):
    if isinstance(text_or_sentences, str):
        return split_sentences(text_or_sentences)
    if isinstance(text_or_sentences, (list, tuple)) and all(isinstance(piece, str) for piece in text_or_sentences):
        return list(text_or_sentences)
    raise AppError("CONTENT_INVALID", {"항목": item}, detail="글(문자열)이나 문장의 목록(list·tuple)이어야 한다")


def _user_keys(user_sentences):
    """사용자가 입력한 글의 열쇠(정규화한 글) — 목록의 항목 하나하나, 한 덩어리 글이면 문장 하나하나와 글 전체."""
    pieces = _sentences(user_sentences, "사용자가 입력한 글")
    if isinstance(user_sentences, str):
        pieces = [*pieces, user_sentences]
    return frozenset(key for key in (flat(piece) for piece in pieces) if key)


def _scan(text_or_sentences, experience_given, user_sentences, with_reviews):
    sentences = _sentences(text_or_sentences)
    exempt = _user_keys(user_sentences) if experience_given else frozenset()
    claims, reviews = [], 0
    for position, sentence in enumerate(sentences):
        scanned = _MENTION.sub(_mention_mask, sentence) if _QUOTE_MARKS.search(sentence) else sentence
        flat_sentence = flat(scanned)
        if len(flat_sentence) < MIN_FLAT:
            continue
        original = flat_sentence if scanned is sentence else flat(sentence)
        found = _violations(scanned, flat_sentence)
        if found and exempt and _exempt(sentence, original, exempt):
            found = []
        for category, word in found:
            claims.append(Claim(category, position, word))
        if with_reviews and reviews < MAX_FINDINGS:
            for category, word in _reviews(sentence, original):
                if reviews >= MAX_FINDINGS:
                    break
                claims.append(Claim(category, position, word))
                reviews += 1
    return tuple(claims)


def _exempt(sentence, flat_sentence, exempt):
    """사용자가 입력한 문장과 정규화한 글이 똑같은가 — 계획이 사용자 입력을 되풀이하는 줄 `이름(입력): 내용` 은 이름을 떼고 내용만 견준다."""
    if flat_sentence in exempt:
        return True
    if "(입력" in sentence:
        match = _ECHO_LABEL.match(sentence)
        if match and flat(sentence[match.end():]) in exempt:
            return True
    return False


def find_claims(text_or_sentences, *, experience_given=False, user_sentences=()):
    """글(한 덩어리 글자 또는 문장 목록)에서 지어낸 것으로 보이는 말을 찾아 `Claim(분류, 문장 번호, 근거 낱말)` 의 튜플로 돌려준다(문장 번호 순, 한 문장 안에서는 위반이 먼저).
    위반(`VIOLATIONS`)과 확인 권장(`REVIEWS`)이 함께 나오며 `is_violation(claim.category)` 로 가른다. 글이 한 덩어리면 `split_sentences` 로 나눈 번호이고, 목록이면 그 목록의 번호다.

    `experience_given=True`(사용자가 경험을 입력했다)면 `user_sentences`(사용자가 입력한 글 — 한 덩어리 글자나 목록)의 문장과 **정규화한 글이 똑같은 문장**만 위반에서 뺀다(띄어쓰기·기호·대소문자 차이는 무시). 부분만 겹치는 문장은 빼지 않는다. 그 밖의 문장은 그대로 검사한다. `experience_given=False` 면 `user_sentences` 를 보지 않는다(경험을 입력하지 않았는데
    경험이 나오면 어디에서 왔든 위반). 확인 권장은 이 예외와 상관없이 나오고 `MAX_FINDINGS`(500)건까지이며, **위반에는 상한이 없다**. 비밀·파일·네트워크는 쓰지 않는다."""
    return _scan(text_or_sentences, experience_given, user_sentences, True)


def find_violations(text_or_sentences, *, experience_given=False, user_sentences=()):
    """`find_claims` 중 위반(막아야 하는 것)만 — 확인 권장은 아예 찾지 않아 더 빠르다."""
    return _scan(text_or_sentences, experience_given, user_sentences, False)


def find_reviews(text_or_sentences):
    """`find_claims` 중 확인 권장(막지 않는 것)만 — 가격·날짜·시각·통계."""
    return tuple(claim for claim in find_claims(text_or_sentences) if not is_violation(claim.category))


