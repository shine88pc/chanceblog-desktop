_CONNECT = frozenset({"와", "과", "및", "이나", "나", "랑", "이랑", "하고"})                       # 낱말을 이어 주는 조사 — 뒤에 남는 낱말이 있을 때만 앞 낱말에 붙여 둔다
_CONNECT_PAIRS = {"와": ("과", "와"), "과": ("과", "와"), "랑": ("이랑", "랑"), "이랑": ("이랑", "랑"), "나": ("이나", "나"), "이나": ("이나", "나")}      # (받침 뒤, 받침 없는 뒤)
_CASE = frozenset({"을", "를", "은", "는", "이", "가", "의", "도", "에", "에서", "에서는", "에는", "로", "으로", "만", "까지", "부터", "라는", "이라는", "란", "이란", "엔", "과의", "와의", "이야기", "이야기를"})


def premise_of(*texts):
    """후보의 글(주제·핵심 키워드·보조 키워드)이 전제한 경험 형식 → Replacement(없으면 None). 가장 구체적인 것 하나."""
    plain = " ".join(squash(text) for text in texts if text)
    raw = " ".join(str(text) for text in texts if text).casefold()
    if _INFO_ARTICLE.search(plain) and not any(word in plain for word in _EXPERIENCED):          # '후기 작성 방법' 같은 정보 글은 후기를 쓴 글이 아니다
        return None
    for replacement, words in PREMISE_RULES:
        if (any(word in plain for word in words) or (replacement.kind in _PREMISE_REGEX and _PREMISE_REGEX[replacement.kind].search(plain))
                or (replacement.kind in _ENGLISH_RULES and _ENGLISH_RULES[replacement.kind].search(raw))):
            return replacement
    return None


def _has_final(text):
    """낱말 끝 글자에 받침이 있는가(한글은 받침, 숫자는 읽는 소리, 영문은 글자 이름 엘·엠·엔·알)."""
    for char in reversed(text):
        if "가" <= char <= "힣":
            return (ord(char) - 0xAC00) % 28 != 0
        if char.isdigit():
            return char in "013678"
        if char.isalpha():
            return char.casefold() in "lmnr"
    return False


def _joined(previous, connective):
    """앞 낱말에 이어 붙일 조사 — '노트북' 뒤에는 '과', '구매' 뒤에는 '와'."""
    pair = _CONNECT_PAIRS.get(connective)
    return previous + (connective if pair is None else (pair[0] if _has_final(previous) else pair[1]))


def _strip_words(plain):
    """한 낱말에서 경험 전제 낱말을 지우고 남은 글 — 가장 긴 낱말부터 지운다."""
    cleaned = plain
    for word in sorted(_PREMISE_WORDS, key=len, reverse=True):
        if word in cleaned:
            cleaned = cleaned.replace(word, "")
    return cleaned.strip(_PUNCT)


def _prepared(text):
    """걷어 내기 전에 글을 손본다 — 띄어 쓴 서술어를 붙이고('써 봤습니다'), 후기 앞의 기간('한 달')과 '느낀 점' 을 지운다."""
    joined = _SPLIT_VERB.sub(lambda match: match.group(1), text)
    return _DURATION.sub(" ", _FELT.sub(" ", joined))


def strip_premise(text):
    """제목·소제목에 쓸 글에서 경험 전제 낱말(후기·체험·직접 …)을 **낱말 단위로** 걷어 낸다 — 경험을 보고하는 서술어('써봤어요'·'다녀왔어요')는 어미째 빼고, 후기에 붙어 있던 조사는 정리한다
    ('로봇청소기 구매 후기와 장단점' → '로봇청소기 구매와 장단점', '신형 노트북 언박싱과 후기' → '신형 노트북'). 결과가 비면 ''."""
    kept, removed, pending = [], False, ""
    for token in _prepared(str(text)).split():
        plain = token.strip(_PUNCT)
        if not plain:
            removed = removed or bool(token)
            continue
        if _EXPERIENCE_VERB.fullmatch(plain) or _SINCERE.fullmatch(plain) or plain.casefold() in _ENGLISH_PREMISE:
            removed = True
            continue
        cleaned = _strip_words(plain)
        if cleaned != plain:
            removed = True
            if cleaned in _CONNECT:                                          # '후기와' → 와 — 뒤에 남는 낱말이 있으면 앞 낱말에 붙인다
                pending = cleaned
                continue
            if not cleaned or cleaned in _CASE or cleaned in _DANGLING:      # '후기를'·'사용후기' 에서 '후기' 를 걷고 남은 조사·'사용' 은 함께 뺀다
                if (not cleaned or cleaned in _CASE) and kept and kept[-1] in _DANGLING:           # '사용 후기를' — 후기 앞에 남은 동작 낱말도 함께 뺀다('구매 후기와 …' 처럼 이어 주는 조사가 오면 남긴다)
                    kept.pop()
                continue
        if pending and kept:
            kept[-1] = _joined(kept[-1], pending)
        pending = ""
        kept.append(cleaned)
    if removed:
        while kept and kept[-1] in _DANGLING:
            kept.pop()
    return " ".join(kept)


